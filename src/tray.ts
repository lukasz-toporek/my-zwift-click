// Menu item indices
const IDX_STATUS = 0;
// IDX_SEP = 1
const IDX_EXIT = 2;

let connectedCount = 0;
let trayRef: SysTray | null = null;

function updateTrayStatus(): void {
  if (!trayRef) return;
  const title = connectedCount > 0
    ? `Connected (${connectedCount} device${connectedCount > 1 ? 's' : ''})`
    : 'Scanning for Zwift Click…';
  trayRef.sendAction({ type: 'update-item', seq_id: IDX_STATUS, item: { title, tooltip: title, enabled: false } })
    .catch(() => { /* tray may already be closing */ });
}

async function main(): Promise<void> {
  const configPath = ensureConfig();
  const config = loadConfig(configPath);
  if (config.debug) setDebugMode(true);
  log.info(`my-zwift-click v${VERSION} [tray]`);
  log.info(`Config: ${configPath}`);

  const shifter = new Shifter(config);
  const handleButtons = (state: ButtonState) => shifter.handleButtonState(state);

  const scanner = new ClickScanner({
    scanTimeoutMs: config.click.scan_timeout_ms,
    reconnectDelayMs: config.click.reconnect_delay_ms,
    keepaliveMs: config.click.keepalive_interval_ms,
  });

  scanner.on('buttons', handleButtons);
  scanner.on('deviceConnected', (id: string) => {
    shifter.reset(); connectedCount++;
    log.info(`Device connected: ${id.slice(-4).toUpperCase()}`);
    updateTrayStatus();
  });
  scanner.on('deviceDisconnected', (id: string) => {
    shifter.reset(); connectedCount = Math.max(0, connectedCount - 1);
    log.warn(`Device disconnected: ${id.slice(-4).toUpperCase()}`);
    updateTrayStatus();
  });

  log.info('Initializing tray icon...');
  const tray = new SysTray({
    menu: {
      icon: ICON_BASE64,
      title: '',
      tooltip: 'my-zwift-click',
      items: [
        { title: 'Scanning for Zwift Click…', tooltip: '', enabled: false },
        SysTray.separator,
        { title: 'Exit', tooltip: 'Stop my-zwift-click', enabled: true },
      ],
    },
    debug: false,
    copyDir: true, // extract Go binary to tmpdir (required inside a pkg bundle)
  });
  trayRef = tray;

  log.info('Waiting for tray ready...');
  await tray.onClick(async (action) => {
    if (action.seq_id === IDX_EXIT) {
      log.info('Shutting down…');
      scanner.stop();
      await tray.kill(false);
      process.exit(0);
    }
  });

  // onClick resolves only after the tray is ready, so start scanning now
  tray.onError((err) => log.error(`Tray error: ${err.message}`));
  log.info('Tray icon ready — starting BLE scan');
  scanner.start();
}

main().catch((err: unknown) => {
  log.error(`Fatal: ${(err as Error).message}`);
  process.exit(1);
});
