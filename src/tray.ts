#!/usr/bin/env node
import './pkg-native-setup'; // MUST be first — patches Module._load before any native addon loads
import * as path from 'path';
import * as fs from 'fs';
import SysTray from 'systray2';
import { loadConfig } from './config/loader';
import { setDebugMode, setLogFile, log } from './logger';
import { ClickScanner } from './ble/scanner';
import { Shifter } from './gear/shifter';
import type { ButtonState } from './ble/protocol/parser';

const VERSION = '0.1.0';
const isPkg = !!(process as NodeJS.Process & { pkg?: unknown }).pkg;

// In pkg bundles, the exe directory is where side-car files (prebuilds/, traybin/) live.
// Changing CWD ensures path.join('.', 'traybin', ...) in systray2 resolves correctly.
const exeDir = isPkg ? path.dirname(process.execPath) : process.cwd();
if (isPkg) {
  process.chdir(exeDir);
  setLogFile(path.join(exeDir, 'my-zwift-click.log'));
}

function ensureConfig(): string {
  const cfgPath = path.join(exeDir, 'config.yaml');
  if (!fs.existsSync(cfgPath)) {
    const defaults = [
      'buttons:',
      '  gear_up: PLUS',
      '  gear_down: MIN',
      '',
      'mywhoosh:',
      '  gear_up_key: k',
      '  gear_down_key: i',
      '',
      'click:',
      '  scan_timeout_ms: 15000',
      '  keepalive_interval_ms: 3000',
      '  reconnect_delay_ms: 2000',
      '',
      'debug: false',
    ].join('\n');
    fs.writeFileSync(cfgPath, defaults, 'utf8');
  }
  return cfgPath;
}

